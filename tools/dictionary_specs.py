"""
Curated specifications used by ``tools/build_ilcd_dictionary.py``.

This module is *build-time* knowledge. The build script combines it with the
machine-readable ILCD / ILCD+EPD reference material in the ``ILCD pdf`` folder
(field table, indicator UUID lists, unit groups, enumerations, categories)
and writes everything into ``data/epd_dictionary.json``. The Streamlit app
only reads the generated JSON, so nothing in here is imported at runtime.

Sources for the curated parts
------------------------------
* Step 1 (DGNB parameter list) and Step 3 (column list) come from
  "Claude instruction 1.docx" in the thesis project.
* ILCD+EPD XPaths are copied verbatim from the field table of
  ``ILCD-EPD-Data-Format-release-v1.3/doc/asciidoc/ilcd-epd-v1.3.adoc``.
  The build script refuses to run if a path listed here does not exist there.
* ECO Platform programme operators: https://www.eco-platform.org/the-eco-epd-programs.html
  (list checked September 2026).
* Danish BR18/BR25 LCA conventions (50-year reference study period,
  kg CO2e/m2/year): One Click LCA help article "Denmark: Bygningsreglementet
  (BR25) and LCA" (checked September 2026).
* ÖKOBAUDAT category ids: ``sample_data/OEKOBAU.DAT_Categories.xml``.
"""

